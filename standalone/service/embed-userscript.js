// Packages the built userscript into the service so the .wgt is self-contained.
// Run before rolldown; the output is required by userScript.ts and inlined
// into dist/index.js by the bundler.

const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..', '..');
const bundlePath = path.join(root, 'dist', 'userScript.js');
const manifestPath = path.join(root, 'package.json');
const outPath = path.join(__dirname, 'userScript.generated.js');

if (!fs.existsSync(bundlePath)) {
    console.error('[embed] Missing ' + bundlePath);
    console.error('[embed] Build it first:  cd mods && npm install && npm run build');
    process.exit(1);
}

const source = fs.readFileSync(bundlePath, 'utf8');
const version = JSON.parse(fs.readFileSync(manifestPath, 'utf8')).version;

// JSON.stringify produces a valid JS string literal for any content.
fs.writeFileSync(outPath,
    '// Generated by embed-userscript.js at build time. Do not edit, do not commit.\n'
    + 'module.exports = {\n'
    + '    version: ' + JSON.stringify(version) + ',\n'
    + '    source: ' + JSON.stringify(source) + '\n'
    + '};\n');

console.log('[embed] Packaged userScript v' + version + ' (' + Math.round(source.length / 1024) + ' KB)');
